from app.agent.config import Limits
from app.agent.models import RunRequest
from app.extras import describe

SYSTEM_PROMPT = """Ты — агент-закупщик сети суши- и пицца-доставки. Твоя задача: найти в интернете реальных \
поставщиков нужного продукта; по каждому нужно собрать полные данные.

Как работать:
1. Ищи через search_web, меняя формулировки: «<продукт> оптом производитель <город>», «<продукт> поставщик для \
ресторанов <регион>» и т. п. Сначала выбранный регион, затем соседние.
2. Нужны сайты самих поставщиков: производителей, дистрибьюторов, оптовиков. Не нужны магазины для физлиц, \
маркетплейсы, доски объявлений, каталоги-перепродавцы и справочники организаций.
3. Подходящие сайты из выдачи передавай в research_suppliers (до 3 адресов за раз). Этот инструмент сам изучает сайт: \
открывает главную, контакты, о компании, доставку, прайс и сертификаты, выделяет данные с цитатами, а чего не хватает, \
ищет по самому сайту. Вручную открывать страницы и сохранять поля не нужно.
4. По результату смотри, что не найдено на сайте. Нужно собрать по каждому поставщику: название, контакты (телефон, email), \
адрес, чем занимается, регионы работы, условия доставки, минимальный заказ, примерную цену, сертификаты. Если часть \
данных на сайте действительно нет, это нормально: так и будет записано, ничего не выдумывается.
5. Изучай поставщиков по очереди партиями по 2–3 сайта. Не завершай после первой находки: в выдаче обычно несколько \
подходящих сайтов. Если сайты из выдачи кончились, измени формулировку поиска.
6. Когда нужное число поставщиков изучено или поиск действительно ничего нового не даёт, вызови finish с кратким итогом.

Ограничено число шагов и расходов: не повторяй одинаковые запросы и не изучай один сайт дважды."""


def build_messages(request: RunRequest, limits: Limits, places_enabled: bool) -> list[dict]:
    if request.regions:
        lines = [
            f"{n}. {region.name}" + (" (основной регион)" if region.role == "primary" else " (соседний)")
            for n, region in enumerate(request.regions, start=1)
        ]
        where = "Регионы поиска по приоритету:\n" + "\n".join(lines)
        if request.city:
            where = (f"Город закупки: {request.city}. Ищи прежде всего поставщиков в этом городе и называй город в запросах "
                     f"(«<продукт> оптом {request.city}»), затем регион.\n{where}")
    else:
        where = "Регион не выбран: ищи по всей России."
    synonyms = f"\nДругие названия: {', '.join(request.synonyms)}." if request.synonyms else ""
    kind = f"\nТип поставщика: {request.supplier_type}." if request.supplier_type else ""
    places = "\nМожно также искать организации в 2GIS через search_places." if places_enabled else ""
    wishes = describe(request.extras)
    needs = (
        "\nДополнительные требования закупщика: " + "; ".join(wishes) + ". Если на сайте есть подтверждение этих требований "
        "(сертификаты, условия хранения и доставки), включи его в данные. Поставщика без подтверждения не отбрасывай."
        if wishes else ""
    )
    user = (
        f"Продукт для закупки: {request.category}.{synonyms}\n{where}{kind}{needs}\n"
        f"Найди и сохрани до {request.target} поставщиков. Шагов у тебя не больше {limits.max_turns}.{places}"
    )
    return [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": user}]
